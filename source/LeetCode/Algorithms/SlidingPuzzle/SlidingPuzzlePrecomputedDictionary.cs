    /// <summary>
    ///     Time complexity - O(1)
    ///     Space complexity - O(1)
    /// </summary>
    /// <param name="board"></param>
    /// <returns></returns>
    public int SlidingPuzzle(int[][] board)
    {
        var id = 0;

        for (var i = 0; i < 2; i++)
        {
            for (var j = 0; j < 3; j++)
            {
                id = (id * 10) + board[i][j];
            }
        }

        return _movesDictionary.GetValueOrDefault(id, -1);
    }
